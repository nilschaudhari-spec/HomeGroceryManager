  final ValueNotifier<AppLanguage> currentLanguageNotifier =
      ValueNotifier<AppLanguage>(supportedLanguages.first);

  AppLanguage get currentLanguage => currentLanguageNotifier.value;

  Future<void> initialize() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedCode = prefs.getString(_prefKey);
      if (savedCode != null) {
        final match = supportedLanguages.firstWhere(
          (l) => l.code == savedCode,
          orElse: () => supportedLanguages.first,
        );
        currentLanguageNotifier.value = match;
      }
    } catch (e) {
      debugPrint('[AppLanguageService] initialize error: $e');
    }
  }

  Future<void> setLanguage(AppLanguage language) async {
    currentLanguageNotifier.value = language;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, language.code);
    } catch (e) {
      debugPrint('[AppLanguageService] setLanguage error: $e');
    }
  }

  Future<void> setLanguageByCode(String code) async {
    final match = supportedLanguages.firstWhere(
      (l) => l.code == code,
      orElse: () => supportedLanguages.first,
    );
    await setLanguage(match);
  }

  static String t(String key, {Map<String, String>? params}) {
    final langCode = instance.currentLanguage.code;
    final dict = _translations[langCode] ?? _translations['en']!;
    var val = dict[key] ?? _translations['en']![key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        val = val.replaceAll('{$k}', v);
      });
    }
    return val;
  }

